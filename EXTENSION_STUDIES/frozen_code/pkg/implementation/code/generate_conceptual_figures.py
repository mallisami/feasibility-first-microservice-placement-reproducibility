#!/usr/bin/env python3
"""Materialize the two frozen manuscript schematics and regenerate the supporting topology figure.

Figures 1 and 2 are manually authored vector assets rather than data-derived plots. Their
font-outlined submission PDFs are retained under provenance/manual_figure_sources and are
copied into the active paper tree here. The controlled topology schematic remains generated
programmatically. Quantitative result figures are generated by the dedicated result scripts.
"""
from __future__ import annotations

from pathlib import Path
import sys
import shutil
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, Circle, Polygon

sys.path.insert(0, str(Path(__file__).resolve().parent))
import figure_style

REPO = Path(__file__).resolve().parents[2]
FIG_DIR = REPO / "PAPER" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)

# These are dense schematic diagrams (15-20 packed text labels per figure), a different
# figure type from the data plots elsewhere. Canvas size and font FAMILY match the shared
# house style; individual label sizes stay hand-tuned to fit their boxes rather than being
# forced to a single size, which would overflow the smaller boxes and break the layout.
figure_style.apply()
plt.rcParams.update({"axes.titlesize": figure_style.FONT_SIZE})

NAVY = "#1f4e79"
BLUE = "#2f75b5"
LIGHT_BLUE = "#d9eaf7"
GREEN = "#548235"
LIGHT_GREEN = "#e2f0d9"
ORANGE = "#c55a11"
LIGHT_ORANGE = "#fce4d6"
GRAY = "#595959"
LIGHT_GRAY = "#f2f2f2"
RED = "#c00000"


def box(ax, x, y, w, h, text, fc, ec=None, color="white", fs=9.2, weight="bold", radius=0.04):
    patch = FancyBboxPatch(
        (x, y), w, h,
        boxstyle=f"round,pad=0.015,rounding_size={radius}",
        linewidth=1.25, facecolor=fc, edgecolor=ec or fc,
    )
    ax.add_patch(patch)
    ax.text(x + w/2, y + h/2, text, ha="center", va="center", color=color,
            fontsize=fs, fontweight=weight, linespacing=1.12)
    return patch


def arrow(ax, x1, y1, x2, y2, *, color=GRAY, lw=1.4, text=None, text_xy=None):
    ax.annotate("", xy=(x2, y2), xytext=(x1, y1),
                arrowprops=dict(arrowstyle="->", lw=lw, color=color, shrinkA=2, shrinkB=2))
    if text:
        tx, ty = text_xy if text_xy else ((x1+x2)/2, (y1+y2)/2)
        ax.text(tx, ty, text, ha="center", va="center", color=color, fontsize=8.2)


def save(fig, name):
    figure_style.save(fig, FIG_DIR / name)


def _copy_manual_submission_figure(source_name: str, target_name: str) -> None:
    source = REPO / "provenance" / "manual_figure_sources" / source_name
    target = FIG_DIR / target_name
    if not source.is_file():
        raise FileNotFoundError(f"Missing frozen manual figure source: {source}")
    shutil.copy2(source, target)


def fig_architecture():
    _copy_manual_submission_figure(
        "Figure1_submission_vector_outlined.pdf",
        "framework_architecture.pdf",
    )


def fig_algorithm_flow():
    _copy_manual_submission_figure(
        "Figure2_submission_vector.pdf",
        "algorithm_flow.pdf",
    )


def node(ax, x, y, label, fc, r=0.30, fs=7.2):
    c=Circle((x,y),r,facecolor=fc,edgecolor="white",linewidth=1.0,zorder=3)
    ax.add_patch(c)
    ax.text(x,y,label,ha="center",va="center",color="white",fontsize=fs,fontweight="bold",zorder=4)


def edge(ax, a, b):
    ax.plot([a[0],b[0]],[a[1],b[1]],color="#b7b7b7",lw=1.25,zorder=1)


def fig_topologies():
    fig, ax = plt.subplots(figsize=figure_style.FIGSIZE)
    ax.set_xlim(0, 16); ax.set_ylim(0, 9.5); ax.axis("off")

    ax.text(2.65, 9.0, "APP_A: Fan-out", ha="center", fontweight="bold", fontsize=10.0)
    A={"FE":(2.65,7.45), "W":(2.65,5.75), "A1":(1.45,4.05), "A2":(3.85,4.05), "C":(1.45,2.15), "D":(3.85,2.15)}
    for u,v in [("FE","W"),("FE","A1"),("FE","A2"),("W","A1"),("W","A2"),("A1","C"),("A1","D"),("A2","C"),("A2","D")]: edge(ax,A[u],A[v])
    for k,(x,y) in A.items(): node(ax,x,y,k, BLUE if k not in {"C","D"} else (GREEN if k=="C" else ORANGE),r=.31,fs=7.2)
    ax.text(2.65,1.30,"FE frontend | W worker | A1/A2 APIs | C cache | D data\n6 replicas",ha="center",color=GRAY,fontsize=6.9,linespacing=1.2)

    ax.text(8.0, 9.0, "APP_B: Mesh", ha="center", fontweight="bold", fontsize=10.0)
    B=[(8.0,7.45),(6.65,6.5),(9.35,6.5),(6.45,4.45),(8.0,4.45),(9.55,4.45),(8.0,2.15)]
    edges=[(0,1),(0,2),(0,4),(1,3),(1,4),(2,4),(2,5),(3,4),(4,5),(3,6),(5,6)]
    for i,j in edges: edge(ax,B[i],B[j])
    for i,(x,y) in enumerate(B,1): node(ax,x,y,f"S{i}","#5b6fc7",r=.31,fs=7.0)
    ax.text(8.0,1.30,"7 service replicas",ha="center",color=GRAY,fontsize=7.4)

    ax.text(13.25, 9.0, "APP_C: Pipeline", ha="center", fontweight="bold", fontsize=10.0)
    xs=[11.25,12.55,13.85,15.15]; labels=["Ingest","Parse","Enrich","Store"]
    ys=[6.55,4.35]; colors=[NAVY,"#2f9ee5","#4caf50","#fb8c00"]
    for stage in range(4):
        for row in range(2): node(ax,xs[stage],ys[row],labels[stage][0],colors[stage],r=.27,fs=7.8)
        ax.text(xs[stage],3.35,labels[stage],ha="center",fontsize=7.0,color=GRAY)
    for stage in range(3):
        for y1 in ys:
            for y2 in ys: edge(ax,(xs[stage],y1),(xs[stage+1],y2))
    ax.text(13.2,1.30,"8 replicas (2 per stage)",ha="center",color=GRAY,fontsize=7.4)

    ax.text(8.0,0.38,"Controlled fixtures used only for supporting mechanism-level comparisons",
            ha="center",fontsize=7.8,color=GRAY,fontstyle="italic")
    save(fig, "benchmark_topologies.pdf")

def main():
    fig_architecture(); fig_algorithm_flow(); fig_topologies()
    print(f"Materialized frozen Figures 1-2 and regenerated supporting topology figure in {FIG_DIR}")

if __name__ == "__main__":
    main()
