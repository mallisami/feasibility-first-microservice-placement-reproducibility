#!/usr/bin/env python3
"""Paired nonparametric bootstrap sensitivity for the primary R1 P95 contrasts.

This is a post-freeze re-analysis of the frozen raw R1 cells. It resamples the
30 paired B+ Exact - Current replicate differences within each condition and
reports a percentile 95% interval for the paired mean difference. No system
experiment is rerun and no outcome is used to retune the scheduler.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd

METHODS = ("Current", "BPlus-Exact")
DEFAULT_SEED = 20260915
DEFAULT_RESAMPLES = 100_000


def accepted_result(method_dir: Path) -> dict:
    accepted = []
    for result_path in sorted(method_dir.glob("attempt-*/result.json")):
        with result_path.open("r", encoding="utf-8") as fh:
            result = json.load(fh)
        if result.get("accepted") is True:
            accepted.append((result_path, result))
    if not accepted:
        raise RuntimeError(f"No accepted attempt under {method_dir}")
    # Match the frozen postprocessor: sorted result paths overwrite duplicate run_id entries,
    # so the lexically last accepted attempt is the canonical row for that run_id.
    return accepted[-1][1]


def condition_differences(condition_dir: Path) -> np.ndarray:
    diffs = []
    replicate_dirs = sorted(condition_dir.glob("replicate-*"))
    for rep_dir in replicate_dirs:
        values = {}
        for method in METHODS:
            result = accepted_result(rep_dir / method)
            values[method] = float(result["application"]["p95_ms"])
        diffs.append(values["BPlus-Exact"] - values["Current"])
    if len(diffs) != 30:
        raise RuntimeError(
            f"{condition_dir.name}: expected 30 paired accepted replicates, found {len(diffs)}"
        )
    return np.asarray(diffs, dtype=float)


def paired_percentile_bootstrap_mean_ci(
    diffs: np.ndarray, *, resamples: int, seed: int
) -> tuple[float, float]:
    rng = np.random.default_rng(seed)
    means = np.empty(resamples, dtype=float)
    chunk = min(10_000, resamples)
    for start in range(0, resamples, chunk):
        n = min(chunk, resamples - start)
        idx = rng.integers(0, diffs.size, size=(n, diffs.size))
        means[start : start + n] = diffs[idx].mean(axis=1)
    lo, hi = np.quantile(means, [0.025, 0.975])
    return float(lo), float(hi)


def latex_escape_condition(name: str) -> str:
    return name.replace("-", " ").title().replace("With", "with")


def write_latex(df: pd.DataFrame, path: Path, resamples: int) -> None:
    lines = [
        "% Auto-generated by implementation/code/r1_p95_bootstrap_sensitivity.py.",
        "% Post-freeze sensitivity using frozen R1 raw accepted cells; no new experiment.",
        "\\begin{table}[htbp]",
        "\\centering",
        (
            "\\caption{Paired nonparametric bootstrap sensitivity for the nine primary R1 "
            f"MAPE-CAP-WS Exact--Current P95 contrasts ({resamples:,} fixed-seed paired resamples per "
            "condition). The bootstrap resamples the 30 paired replicate differences and reports "
            "a percentile 95\\% interval for the paired mean. All intervals include zero; this "
            "supports the same uncertainty conclusion as the Student-$t$ intervals and is not "
            "an equivalence test.}"
        ).replace(",", "{,}", 1),
        "\\label{tab:r1-bootstrap-sensitivity}",
        "\\scriptsize",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Condition & $n$ & Mean $\\Delta$ P95 (ms) & Bootstrap 95\\% CI (ms) \\\\",
        "\\midrule",
    ]
    for row in df.itertuples(index=False):
        condition = latex_escape_condition(row.condition)
        lines.append(
            f"{condition} & {int(row.n)} & {row.mean_diff_ms:.1f} & "
            f"[{row.bootstrap_lo_ms:.1f}, {row.bootstrap_hi_ms:.1f}] \\\\" 
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--resamples", type=int, default=DEFAULT_RESAMPLES)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()

    root = args.root.resolve()
    raw_root = root / "RESULTS/primary/v03-20260811T151500Z/raw/r1"
    forest_path = root / "RESULTS/primary/v03-20260811T151500Z/derived/r1_p95_forest_source.csv"
    out_csv = root / "RESULTS/primary/v03-20260811T151500Z/derived/statistics/r1_p95_paired_bootstrap_sensitivity.csv"
    out_tex = root / "PAPER/tables/v03/r1_p95_bootstrap_sensitivity.tex"

    forest = pd.read_csv(forest_path).set_index("group")
    rows = []
    for idx, condition_dir in enumerate(sorted(p for p in raw_root.iterdir() if p.is_dir())):
        condition = condition_dir.name
        diffs = condition_differences(condition_dir)
        mean_diff = float(diffs.mean())
        expected = float(forest.loc[condition, "paired_mean_difference"])
        if not np.isclose(mean_diff, expected, atol=1e-9):
            raise RuntimeError(
                f"{condition}: raw-data mean difference {mean_diff} does not match frozen source {expected}"
            )
        lo, hi = paired_percentile_bootstrap_mean_ci(
            diffs, resamples=args.resamples, seed=args.seed + idx
        )
        rows.append(
            {
                "condition": condition,
                "n": int(diffs.size),
                "mean_diff_ms": mean_diff,
                "student_t_lo_ms": float(forest.loc[condition, "ci95_low"]),
                "student_t_hi_ms": float(forest.loc[condition, "ci95_high"]),
                "bootstrap_lo_ms": lo,
                "bootstrap_hi_ms": hi,
                "bootstrap_contains_zero": bool(lo <= 0.0 <= hi),
                "resamples": int(args.resamples),
                "seed": int(args.seed + idx),
            }
        )

    df = pd.DataFrame(rows)
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_csv, index=False)
    write_latex(df, out_tex, args.resamples)

    if not bool(df["bootstrap_contains_zero"].all()):
        raise SystemExit("At least one bootstrap interval excludes zero; inspect before publication.")
    print(df.to_string(index=False))
    print(f"Wrote {out_csv}")
    print(f"Wrote {out_tex}")


if __name__ == "__main__":
    main()
